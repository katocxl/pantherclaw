// The draft package (G0 M15 D23, HR-416). It is a starting point for a
// person, never a reviewed package: every operation has empty effects, an
// empty summary and an empty mapping description, so it fails manifest
// validation until a person fills them in. Upstream descriptions are
// UNTRUSTED and appear only in comments, never in a description field.

// DraftVersion is the version of every draft package.
const DraftVersion = "0.0.0-draft"

// draftName is the draft package's name: draft.<connection-name-slug>.
func draftName(connection string) string {
	return "draft." + slug(connection, '-')
}

// slug lowercases s and replaces every run of other characters with sep.
func slug(s string, sep rune) string {
	var b strings.Builder
	last := sep
	for _, r := range strings.ToLower(s) {
		if r < unicode.MaxASCII && (unicode.IsLetter(r) || unicode.IsDigit(r)) {
			b.WriteRune(r)
			last = r
		} else if last != sep {
			b.WriteRune(sep)
			last = sep
		}
	}
	out := strings.Trim(b.String(), string(sep))
	if out == "" || out[0] < 'a' || out[0] > 'z' {
		out = "x" + string(sep) + out
	}
	return strings.TrimRight(out[:min(len(out), 48)], string(sep))
}

// quote is s as a YAML double-quoted scalar (a JSON string is one).
func quote(s string) string {
	b, _ := json.Marshal(s)
	return string(b)
}

// untrusted writes the upstream description as comment lines, each marked
// UNTRUSTED, with control characters dropped so it cannot leave the
// comment.
func untrusted(b *strings.Builder, indent, desc string) {
	clean := strings.Map(func(r rune) rune {
		switch {
		case r == '\n':
			return r
		case unicode.IsControl(r), unicode.Is(unicode.Cf, r), r == ' ', r == ' ':
			return ' '
		}
		return r
	}, desc)
	if strings.TrimSpace(clean) == "" {
		return
	}
	for line := range strings.SplitSeq(clean, "\n") {
		fmt.Fprintf(b, "%s# UNTRUSTED upstream description: %s\n", indent, strings.TrimRight(line, " "))
	}
}

// draft builds the manifest of a draft package from rows.
func draft(conn dbq.PcConnection, rows []dbq.PcConnectionInventory) Draft {
	name := draftName(conn.Name)
	var b strings.Builder
	var todo []string
	fmt.Fprintf(&b, "# DRAFT package generated by PantherClaw from the discovery inventory of connection %s (%s).\n",
		quote(conn.Name), conn.ID)
	b.WriteString("# It is UNSIGNED and does not validate: fill in every TODO, sign it with an org package key,\n" +
		"# import it and review it. Descriptions below marked UNTRUSTED come from the upstream server.\n")
	fmt.Fprintf(&b, "format: 1\nname: %s\nversion: %s\npublisher: \"\" # TODO\nsummary: \"\" # TODO\n\ndefinitions:\n", quote(name), quote(DraftVersion))
	todo = append(todo, "publisher and summary of the package")
	used := map[string]int{}
	for _, r := range rows {
		op := slug(r.Name, '_')
		if used[op]++; used[op] > 1 {
			op = fmt.Sprintf("%s_%d", op, used[op])
		}
		op = "draft." + op
		route := strings.ReplaceAll(op[len("draft."):], "_", "-")
		untrusted(&b, "  ", r.Description)
		fmt.Fprintf(&b, "  - operation: %s\n    summary: \"\" # TODO\n", quote(op))
		if r.Kind == InventoryTool {
			b.WriteString("    access: write\n")
		} else {
			b.WriteString("    access: read\n")
		}
		b.WriteString("    target: # TODO\n      type: \"\"\n      id_pattern: \"\"\n      account: none\n" +
			"    params: {} # TODO\n    effects: [] # TODO\n    reversibility: irreversible # TODO\n" +
			"    retry:\n      safe: false\n      on_unknown: fail\n" +
			"    assurance:\n      basis: declared\n      reviewed_by: [] # TODO\n      valid_until: \"\" # TODO\n    mappings:\n")
		switch r.Kind {
		case InventoryTool:
			fmt.Fprintf(&b, "      - channel: mcp\n        tool: %s\n        route: %s\n        description: \"\" # TODO\n"+
				"        input_schema: {} # TODO\n        extract: # TODO\n          target_id: \"\"\n          params: {}\n", quote(r.Name), quote(route))
			fmt.Fprintf(&b, "    dispatch:\n      mcp:\n        tool: %s\n        upstream_digest: %s\n        arguments: {} # TODO\n",
				quote(r.Name), quote(r.Digest))
			todo = append(todo, fmt.Sprintf("%s (tool %s): summary, target, params, effects, mapping description, input schema, extract and arguments", op, r.Name))
		default:
			fmt.Fprintf(&b, "      - channel: mcp_resource\n        resource: %s\n        route: %s\n        extract: # TODO\n"+
				"          target_id: \"\"\n          params: {}\n", quote(r.Name), quote(route))
			fmt.Fprintf(&b, "    dispatch:\n      mcp:\n        resource: %s\n", quote(r.Name))
			todo = append(todo, fmt.Sprintf("%s (resource %s): summary, target, params, effects and extract", op, r.Name))
		}
	}
	todo = append(todo, "assurance of every operation", "sign with an org package key, import, and review the version")
	return Draft{Manifest: []byte(b.String()), Todo: todo}
}
