var update = flag.Bool("update", false, "regenerate builtin/manifest.json and digest.go")

// Version is the built-in pack's version.
const version = "1"

func env(t *testing.T) *celenv.Env {
	t.Helper()
	e, err := engine.NewEnv(celenv.DefaultLimits)
	if err != nil {
		t.Fatal(err)
	}
	return e
}

// TestPackDigestIsCurrent regenerates the manifest and the PackDigest
// constant from builtin/ and fails when the committed ones are stale, so
// task check catches an edited rule whose manifest was not regenerated
// (D12). Run `go test ./internal/detection/pack -run TestPackDigestIsCurrent
// -update` after changing a rule.
func TestPackDigestIsCurrent(t *testing.T) {
	manifest, err := BuildManifest(os.DirFS("builtin"), version)
	if err != nil {
		t.Fatal(err)
	}
	sum := sha256.Sum256(manifest)
	digest := []byte(fmt.Sprintf(digestSource, hex.EncodeToString(sum[:])))
	if *update {
		if err := os.WriteFile(filepath.Join("builtin", "manifest.json"), manifest, 0o600); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile("digest.go", digest, 0o600); err != nil {
			t.Fatal(err)
		}
		return
	}
	if got, err := os.ReadFile(filepath.Join("builtin", "manifest.json")); err != nil || !bytes.Equal(got, manifest) {
		t.Errorf("builtin/manifest.json is stale (%v); run this test with -update", err)
	}
	if got, err := os.ReadFile("digest.go"); err != nil || !bytes.Equal(bytes.ReplaceAll(got, []byte("\r\n"), []byte("\n")), digest) {
		t.Errorf("digest.go is stale (%v); run this test with -update", err)
	}
}

const digestSource = `// SPDX-License-Identifier: BUSL-1.1
// Copyright (c) 2026 Joshua Kato. See LICENSE and NOTICE.

// Code generated by TestPackDigestIsCurrent -update. DO NOT EDIT.

package pack

// PackDigest is the hex SHA-256 of builtin/manifest.json.
const PackDigest = %q
`

// TestBuiltinRulesFireAndStayQuiet: every built-in rule loads, has at
// least one firing and one non-firing test, and passes them (D11).
func TestBuiltinRulesFireAndStayQuiet(t *testing.T) {
	p, err := Load(env(t))
	if err != nil {
		t.Fatal(err)
	}
	if p.Version != version || len(p.Rules) < 20 {
		t.Fatalf("pack %s with %d rules", p.Version, len(p.Rules))
	}
	for _, c := range p.Rules {
		t.Run(c.Rule.ID, func(t *testing.T) {
			if err := engine.CheckTests(context.Background(), c); err != nil {
				t.Error(err)
			}
		})
	}
}

// TestPackCoversD11: the rules D11 names are all present, in their
// editions; HR-037's rule is community (never edition-gated).
func TestPackCoversD11(t *testing.T) {
	p, err := Load(env(t))
	if err != nil {
		t.Fatal(err)
	}
	editions := map[string]string{}
	for _, c := range p.Rules {
		editions[c.Rule.ID] = c.Rule.Edition
	}
	community := []string{
		"pc.authority.self_issue", "pc.authority.self_approve", "pc.identity.key_new_network", "pc.tools.drift",
		"pc.tools.description_injection", "pc.approvals.variant_shopping", "pc.integrity.effect_without_receipt",
		"pc.integrity.action_tampered", "pc.integrity.evidence_integrity_failed", "pc.containment.kill_switch_engaged",
		"pc.coverage.lost", "pc.live.first_sensitive_use", "pc.live.significant_write", "pc.live.authority_expanded",
		"pc.live.unexpected_denial",
	}
	business := []string{
		"pc.probing.denial_burst", "pc.sequence.read_then_disclose", "pc.budget.splitting", "pc.delegation.depth_anomaly",
		"pc.drift.behaviour",
	}
	for _, id := range community {
		if editions[id] != "community" {
			t.Errorf("%s: edition %q, want community", id, editions[id])
		}
	}
	for _, id := range business {
		if editions[id] != "business" {
			t.Errorf("%s: edition %q, want business", id, editions[id])
		}
	}
	for _, c := range p.Rules {
		if c.Rule.ID == "pc.integrity.effect_without_receipt" && c.Rule.Attention != reflexdomain.AttentionPage {
			t.Error("integrity rules page")
		}
		if !slices.Contains(append(community, business...), c.Rule.ID) {
			t.Errorf("unexpected rule %s", c.Rule.ID)
		}
	}
}

// TestT105_TamperedPackTurnsDetectionsOff: a rule file edited after the
// manifest, a manifest edited after the build, or an extra rule file all
// fail the integrity check (HR-241).
func TestT105_TamperedPackTurnsDetectionsOff(t *testing.T) {
	read := func(name string) []byte {
		b, err := builtin.ReadFile("builtin/" + name)
		if err != nil {
			t.Fatal(err)
		}
		return b
	}
	base := func() fstest.MapFS {
		m := fstest.MapFS{}
		entries, err := builtin.ReadDir("builtin")
		if err != nil {
			t.Fatal(err)
		}
		for _, e := range entries {
			m["builtin/"+e.Name()] = &fstest.MapFile{Data: read(e.Name())}
		}
		return m
	}
	if _, err := load(base(), PackDigest, env(t)); err != nil {
		t.Fatalf("untouched pack: %v", err)
	}
	edited := base()
	edited["builtin/tools_drift.yaml"].Data = append(bytes.Clone(read("tools_drift.yaml")), []byte("\n# quiet\n")...)
	extra := base()
	extra["builtin/extra_rule.yaml"] = &fstest.MapFile{Data: read("tools_drift.yaml")}
	manifest := base()
	manifest["builtin/manifest.json"].Data = bytes.Replace(read("manifest.json"), []byte(`"version":"1"`), []byte(`"version":"2"`), 1)
	for name, fsys := range map[string]fstest.MapFS{"edited rule": edited, "extra rule": extra, "edited manifest": manifest} {
		if _, err := load(fsys, PackDigest, env(t)); !errors.Is(err, ErrIntegrity) {
			t.Errorf("%s: %v, want ErrIntegrity", name, err)
		}
	}
}

// fires runs one built-in rule over events in order and reports whether it
// raised a signal.
func fires(t *testing.T, id string, events ...rules.TestEvent) bool {
	t.Helper()
	p, err := Load(env(t))
	if err != nil {
		t.Fatal(err)
	}
	for _, c := range p.Rules {
		if c.Rule.ID != id {
			continue
		}
		st := engine.NewMemory()
		fired := false
		for i, te := range events {
			r, err := engine.Evaluate(context.Background(), st, c, engine.TestFeedEvent(int64(i+1), te))
			if err != nil {
				t.Fatal(err)
			}
			fired = fired || r.Fired != nil
		}
		return fired
	}
	t.Fatalf("no rule %s", id)
	return false
}

// TestT017_SensitiveReadThenPublicWriteIsDetected: a run that reads data
// and then writes toward a public destination within 30 minutes raises
// pc.sequence.read_then_disclose; the same writes in another run, after the
// window, or denied, do not.
func TestT017_SensitiveReadThenPublicWriteIsDetected(t *testing.T) {
	read := rules.TestEvent{Kind: "receipt.decision", Decision: "ALLOW", Operation: "crm.customer.read", DestinationClass: "internal",
		Subjects: map[string]string{"run": "r1"}}
	write := rules.TestEvent{Kind: "receipt.decision", Decision: "ALLOW", Operation: "slack.message.post", DestinationClass: "public",
		Subjects: map[string]string{"run": "r1"}, At: "29m"}
	if !fires(t, "pc.sequence.read_then_disclose", read, write) {
		t.Error("read then public write within 30 minutes did not fire")
	}
	late := write
	late.At = "31m"
	other := write
	other.Subjects = map[string]string{"run": "r2"}
	denied := write
	denied.Decision = "DENY"
	internal := write
	internal.DestinationClass = "internal"
	for name, w := range map[string]rules.TestEvent{"late": late, "other run": other, "denied": denied, "internal": internal} {
		if fires(t, "pc.sequence.read_then_disclose", read, w) {
			t.Errorf("%s fired", name)
		}
	}
	if fires(t, "pc.sequence.read_then_disclose", write, read) {
		t.Error("write then read fired")
	}
}

// TestT025_DefinitionDriftIsDetected: a drift report and a drift
// quarantine raise pc.tools.drift; an ordinary package transition does
// not; no rule lifts the quarantine (rules only raise signals).
func TestT025_DefinitionDriftIsDetected(t *testing.T) {
	if !fires(t, "pc.tools.drift", rules.TestEvent{Kind: "audit.connection.drift_reported", Subjects: map[string]string{"connection": "c1"}}) {
		t.Error("drift report did not fire")
	}
	if !fires(t, "pc.tools.drift", rules.TestEvent{Kind: "audit.package.transitioned",
		Attrs: map[string]string{"to": "QUARANTINED", "reason": "upstream_drift"}}) {
		t.Error("drift quarantine did not fire")
	}
	if fires(t, "pc.tools.drift", rules.TestEvent{Kind: "audit.package.transitioned",
		Attrs: map[string]string{"to": "QUARANTINED", "reason": "reviewer"}}) {
		t.Error("a quarantine for another reason fired")
	}
}

